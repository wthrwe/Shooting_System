/**
 * 仿真 HAL 的**注入接口** —— 只有测试主程序用它，产品代码不包含本文件。
 *
 * 这里提供了三样在真实硬件上很难做到、但在桌面上必须做到的事：
 *   1. 把一个字节"塞进"串口（等价于线上真的来了一个字节）
 *   2. 探测**串口是不是已经静默死亡** —— 见 host_dead_rx_count
 *   3. 把发出去的字节抓回来比对
 *
 * 临时验证脚手架，不进版本库、不进 Keil 工程。
 */

#ifndef HOST_FAKE_HAL_H
#define HOST_FAKE_HAL_H

#include "stm32f4xx_hal.h"

/* ============================================================================
 * 一、注入
 * ==========================================================================*/

/** 塞一个字节进指定串口。返回 0 成功；-1 表示该串口**没有处于已武装状态**。 */
int host_uart_inject(UART_HandleTypeDef *huart, uint8_t b);

/** 连续塞 n 个字节（逐个走完整的中断路径，不批处理）。 */
int host_uart_inject_str(UART_HandleTypeDef *huart, const char *s, int n);

/**
 * 模拟一次**接收错误**（过载/帧错/噪声），等价于 HAL 在中断里调用 ErrorCallback。
 *
 * `leave_busy` 非 0 时，故意把 `RxState` **留在 BUSY_RX** 再回调 ——
 * 这正是真实 HAL 出错后最坏的情形，也是 AVE_uart.c 里那段
 * 「先 Abort 再武装」注释针对的场景。取 0 则模拟 HAL 已把状态清干净。
 */
void host_raise_error(UART_HandleTypeDef *huart, uint32_t hal_error_code, int leave_busy);

/* ============================================================================
 * 二、探针 —— 没有探针的测试只会在出事时沉默
 * ==========================================================================*/

/**
 * 🔴 **串口静默死亡次数。**
 *
 * 每当我们想塞一个字节、却发现该串口**没有任何已武装的落脚点**时 +1。
 * 真实硬件上这一刻是无声无息的：线插着、`RxState` 显示 BUSY_RX、什么都收不到。
 * 在这里它是个可断言的数字 —— 于是"漏掉重新武装"这个
 * *本项目最难查的故障模式* 变成了一个能失败的判据。
 */
extern unsigned long host_dead_rx_count;

/** 成功走完"收到字节 → 回调"路径的次数。 */
extern unsigned long host_delivered_count;

/** `HAL_UART_Receive_IT` 返回 HAL_BUSY 的次数（状态没清干净就武装）。 */
extern unsigned long host_rearm_busy_count;

/**
 * `HAL_UART_Transmit*` 因 `gState` 不为 READY 而返回 HAL_BUSY 的次数。
 *
 * 🔴 这是发送方向的"静默死亡"探针，与 `host_dead_rx_count` 对称。
 *    `AVE_uart.c` 里两处代码专门防它：启动失败时把忙标志清回去、
 *    错误回调里顺手 `AbortTransmit`。**这个计数不为 0 就一定有问题** ——
 *    真机上它没有现象，只有"日志不见了"。
 */
extern unsigned long host_tx_busy_count;

/* ============================================================================
 * 三、发送抓包
 * ==========================================================================*/

/** 清空某路的发送抓包缓冲。 */
void host_tx_reset(UART_HandleTypeDef *huart);

/**
 * 取某路已发送的字节数与内容指针（内容不含结尾 '\0'，只保证 `*len` 个字节有效）。
 *
 * ⚠️ 中断发送的内容**只有调过 `host_uart_tx_finish()` 之后才会出现在这里** ——
 *    理由见 stm32f4xx_hal.h 的"第二条保真度"。
 */
const uint8_t *host_tx_data(UART_HandleTypeDef *huart, int *len);

/**
 * 模拟"这一笔中断发送发完了" —— 等价于硬件发完最后一个字节后进中断。
 *
 * 🔴 **它做的是一次真实的拷贝：把 `Transmit_IT()` 当时记下的指针指向的内容
 *    搬进抓包缓冲。** 所以调用方在启动发送之后、调用本函数之前
 *    **覆盖那块内存**，抓到的就会是被覆盖后的内容 —— 这正是要测的：
 *    "产品代码有没有先拷一份自己的缓冲"。若替身提前抄走，这个 bug 永远测不出来。
 *
 * 返回 0 表示确实有一笔在途发送被完成；-1 表示这一路本来就没在发。
 */
int host_uart_tx_finish(UART_HandleTypeDef *huart);

/**
 * 时间流逝 —— 把仍在途的中断发送当作已经发完。**由延时函数调用**
 * （`HAL_Delay` 与仿真 `osDelay`），理由见 fake_hal.c 里的实现说明。
 *
 * ⚠️ `ms == 0` 或调过 `host_uart_tx_hold(1)` 时它什么都不做。
 */
void host_uart_tx_progress(uint32_t ms);

/**
 * 非 0 = 关掉"时间流逝会自动完成在途发送"这条保真。
 *
 * 用途只有一个：构造"上一帧迟迟发不完"的工况，好让
 * `AVE_gimbal.c` 里那条**只在 `EBUSY` 时才走**的重试分支真的被执行一次。
 * 不打开它，那条分支在宿主机上永远走不到 —— 也就永远不知道它写对没有。
 */
void host_uart_tx_hold(int on);

/** 因"时间流逝"而自动完成的中断发送笔数。 */
extern unsigned long host_tx_finish_count;

/* ============================================================================
 * 四、GPIO 记录
 * ==========================================================================*/

/** 取某个引脚**最后一次**被写入的电平；从未写过返回 -1。 */
int host_gpio_last(GPIO_TypeDef *port, uint16_t pin);

/** 该引脚被写过的总次数。 */
unsigned long host_gpio_writes(GPIO_TypeDef *port, uint16_t pin);

/* ============================================================================
 * 四·五、复位原因注入
 * ==========================================================================*/

/**
 * 直接写假 `RCC->CSR`。位定义见 stm32f4xx_hal.h 的 `RCC_FLAG_*`
 * （如 `RCC_FLAG_PORRST | RCC_FLAG_BORRST` 就是上电那一瞬的常态）。
 *
 * ⚠️ 目前**没有用例调用它** —— 它存在是为了让「先读七个标志、再清」
 *    这条顺序约束将来能被写真用例。注意那是一道有门槛的活：
 *    `AVE_Board_ResetCause()` 把结果缓存在 static 里，一个进程只能验一次，
 *    详见 fake_hal.c 里 `host_reset_all()` 的注释。
 */
void host_rcc_set_csr(uint32_t bits);

/* ============================================================================
 * 五、全局复位 —— 每个用例开头调一次
 * ==========================================================================*/

void host_reset_all(void);

#endif /* HOST_FAKE_HAL_H */
